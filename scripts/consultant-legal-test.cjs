const { PGlite } = require('@electric-sql/pglite');
const { pgcrypto } = require('@electric-sql/pglite/contrib/pgcrypto');
const { readFileSync } = require('node:fs');
const { randomUUID } = require('node:crypto');
const assert = require('node:assert/strict');

(async () => {
  const db = new PGlite({ extensions: { pgcrypto } });
  const scalar = async (sql, args = []) => Object.values((await db.query(sql, args)).rows[0])[0];
  const user = async id => { await db.exec('reset role'); await db.query("select set_config('test.uid',$1,false)", [id || '']); await db.exec('set role authenticated'); };
  try {
    await db.exec("create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key,phone text,raw_user_meta_data jsonb default '{}');create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;grant usage on schema auth,public to anon,authenticated;alter default privileges in schema public grant all on tables to authenticated,anon;alter default privileges in schema public grant all on sequences to authenticated,anon;");
    for (const file of ['schema', 'experience', 'wallet', 'partners', 'operations', 'seller_subscriptions', 'influencer_legal_2026_09_12']) await db.exec(readFileSync(`supabase/${file}.sql`, 'utf8'));
    const owner = randomUUID(), other = randomUUID();
    for (const id of [owner, other]) await db.query('insert into auth.users(id,phone) values($1,$2)', [id, id]);
    const app = await scalar("insert into partner_applications(customer_id,role,status) values($1,'consultant','approved') returning id", [owner]);
    const order = await scalar("insert into partner_orders(partner_id,customer_id,role,title,status) values($1,$2,'consultant','Existing appointment','active') returning id", [app, other]);
    const oldConsent = await scalar("insert into consent_events(account_id,partner_application_id,consent_type,version,accepted,consent_text) values($1,$2,'partner_registration','old',true,'Existing consent') returning id", [owner, app]);
    for (const file of ['consultant_legal', 'consultant_legal_drafts_2026_09_20']) await db.exec(readFileSync(`supabase/${file}.sql`, 'utf8'));
    await db.exec(readFileSync('supabase/consultant_legal_drafts_2026_09_20.sql', 'utf8'));
    assert.equal(await scalar("select count(*)::int from legal_documents where version='2026-09-20-draft'"), 2, 'Draft seed is idempotent');
    for (const kind of ['terms', 'privacy']) {
      const content = readFileSync(`src/features/partners/legal/documents/consultant-${kind}-2026-09-20-draft.txt`, 'utf8');
      assert.equal(await scalar('select content from legal_documents where document_key=$1', [`eazily-consultant-provider-${kind === 'terms' ? 'terms' : 'privacy-policy'}`]), content);
    }
    await assert.rejects(db.exec("update legal_documents set published=true,consultant_complete=true,consultant_approved_at=now(),consultant_approved_by='" + owner + "' where version='2026-09-20-draft'"), /drafts cannot be published/);
    assert.equal(await scalar('select status from partner_applications where id=$1', [app]), 'approved');
    assert.equal(await scalar('select count(*)::int from consent_events where id=$1', [oldConsent]), 1);
    await db.query("update partner_orders set status='completed' where id=$1", [order]);
    await assert.rejects(db.query("insert into partner_posts(partner_id,role,status) values($1,'consultant','published')", [app]), /Consultant Terms acceptance/);
    await assert.rejects(db.query("insert into partner_orders(partner_id,customer_id,role,title) values($1,$2,'consultant','New booking')", [app, other]), /Consultant Terms acceptance/);
    await user(owner);
    assert.equal(await scalar("select count(*)::int from legal_documents where version='2026-09-20-draft'"), 0, 'Drafts hidden by RLS');
    const status = () => scalar('select get_consultant_legal_status($1)', [app]);
    assert.equal((await status()).eligible, false);
    const accept = (documents, terms = true, privacy = true) => db.query('select accept_consultant_policies($1,$2,$3,$4)', [app, documents, terms, privacy]);
    await assert.rejects(accept([]), /policies are unavailable/);
    await assert.rejects(accept([], false), /Separate Terms acceptance/);
    await assert.rejects(accept([], true, null), /Separate Terms acceptance/);
    await assert.rejects(db.query("insert into consent_events(account_id,partner_application_id,consent_type,version,accepted,consent_text) values($1,$2,'eazily-consultant-provider-terms','forged',true,'Forged')", [owner, app]), /append-only|row-level security|permission denied/);
    await db.exec('reset role');
    // Synthetic approved documents live only in this disposable in-memory database.
    const publish = async (key, version, effective) => scalar("insert into legal_documents(kind,language,version,title,content,published,effective_at,document_key,consultant_complete,consultant_approved_by,consultant_approved_at) values($1,'English',$2,'TEST ONLY','Synthetic complete fixture',true,$3,$4,true,$5,now()) returning id", [key === 'terms' ? 'terms' : 'privacy_policy', version, effective, `eazily-consultant-provider-${key === 'terms' ? 'terms' : 'privacy-policy'}`, owner]);
    const termsId = await publish('terms', 'test-v1', '2020-01-01');
    await user(owner);
    await assert.rejects(accept([{ id: termsId, version: 'test-v1' }]), /policies are unavailable/);
    await db.exec('reset role');
    await publish('privacy', 'test-v1', '2020-01-01');
    await user(owner);
    const docs = (await status()).documents.map(doc => ({ id: doc.id, version: doc.version }));
    await assert.rejects(accept([{ ...docs[0], version: 'stale' }, docs[1]]), /policies changed/);
    await assert.rejects(accept([docs[0], docs[0]]), /policies changed/);
    await assert.rejects(accept(null), /identifiers and versions/);
    await accept(docs);
    const accepted = await status();
    assert.equal(accepted.eligible, true);
    assert.equal(accepted.acceptances.length, 2);
    assert.ok(accepted.acceptances.every(record => record.account_id === owner && record.legal_document_id && Math.abs(Date.now() - Date.parse(record.recorded_at)) < 10000));
    await accept(docs);
    assert.deepEqual((await status()).acceptances, accepted.acceptances, 'Retries preserve original timestamp and rows');
    await user(other);
    await assert.rejects(status(), /not found/);
    await assert.rejects(accept(docs), /not found/);
    assert.equal(await scalar('select count(*)::int from consent_events where partner_application_id=$1', [app]), 0);
    await user(null);
    await assert.rejects(accept(docs), /Sign in/);
    await db.exec('reset role');
    await assert.rejects(db.query("update legal_documents set content='Changed' where id=$1", [termsId]), /immutable/);
    await assert.rejects(db.query('delete from consent_events where id=$1', [accepted.acceptances[0].id]), /append-only/);
    await assert.rejects(db.query("update consent_events set consent_type='other' where id=$1", [accepted.acceptances[0].id]), /append-only/);
    const post = await scalar("insert into partner_posts(partner_id,role,status) values($1,'consultant','published') returning id", [app]);
    await publish('terms', 'future-v3', '2099-01-01');
    await user(owner);
    assert.equal((await status()).eligible, true, 'Future effective documents do not require early acceptance');
    await db.exec('reset role');
    await publish('terms', 'test-v2', '2021-01-01');
    await user(owner);
    assert.equal((await status()).eligible, false, 'New approved version requires re-acknowledgment');
    await assert.rejects(accept(docs), /policies changed/);
    await db.exec('reset role');
    await assert.rejects(db.query("update partner_posts set details='{}' where id=$1", [post]), /Consultant Terms acceptance/);
    await db.query("update partner_posts set status='paused' where id=$1", [post]);
    await user(owner);
    await accept((await status()).documents.map(doc => ({ id: doc.id, version: doc.version })));
    assert.equal((await status()).acceptances.length, 3, 'Old version consent is retained');
    assert.equal((await status()).eligible, true);
    console.log('PASS: Consultant draft fidelity/RLS/publication block, explicit separate consent, ownership, server timestamp, retries, immutable history, version refresh, future dates, work gates, existing account/appointment preservation.');
  } finally { await db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
