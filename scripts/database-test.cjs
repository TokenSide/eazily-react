const { PGlite } = require('@electric-sql/pglite');
const { pgcrypto } = require('@electric-sql/pglite/contrib/pgcrypto');
const { readFileSync } = require('node:fs');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');

(async () => {
  const db = new PGlite({ extensions: { pgcrypto } });
  try {
    // Local Supabase Auth contract; all application migrations run unmodified.
    await db.exec(`create role anon; create role authenticated;
      create schema auth;
      create table auth.users(id uuid primary key,phone text,raw_user_meta_data jsonb default '{}');
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
      grant usage on schema auth,public to authenticated,anon;
      alter default privileges in schema public grant all on tables to authenticated,anon;
      alter default privileges in schema public grant all on sequences to authenticated,anon;`);
    for (const file of ['schema.sql', 'experience.sql', 'wallet.sql', 'partners.sql', 'operations.sql', 'seller_subscriptions.sql', 'seller_pricing.sql', 'seller_posting.sql', 'seller_workspace.sql', 'seller_finance_extensions.sql', 'seller_hardening.sql', 'seller_gateway.sql']) await db.exec(readFileSync(`supabase/${file}`, 'utf8'));
    const a = randomUUID(), b = randomUUID(), c = randomUUID(), v = randomUUID();
    for (const id of [a, b, c]) await db.query('insert into auth.users(id,phone) values($1,$2)', [id, id]);
    await db.query(`insert into vendors(id,owner_id,business_name,published,service_names,coverage,prices) values($1,$2,'Test Vendor',true,ARRAY['Plumber'],ARRAY['Bhopal'],'{"Plumber":200}')`, [v, a]);
    await db.exec(`insert into service_policies(service_name,fixed_price) values('Plumber',true); update referral_config set enabled=true,reward_amount=80,minimum_payment=1;`);
    const user = async id => { await db.exec('reset role'); await db.query("select set_config('test.uid',$1,false)", [id]); await db.exec('set role authenticated'); };
    const scalar = async (sql, args = []) => Object.values((await db.query(sql, args)).rows[0])[0];
    await user(a);
    const professional = await scalar("select row_to_json(x) from (select * from save_partner_application('professional','{\"name\":\"Partner A\"}',false)) x");
    assert.equal(professional.status, 'draft');
    await assert.rejects(db.query("select save_partner_post('professional','{}','submit',null)"), /approval is required/);
    await assert.rejects(db.query("select set_partner_availability(true)"), /Approved Service Professional/);
    await db.exec('reset role');
    const consultantApplication = randomUUID(), consultantPost = randomUUID();
    await db.exec("update seller_pricing_rules set enabled=true,seller_tax_bps=0,customer_tax_bps=0,fee_tax_bps=0,separate_fee_paise=0,include_visiting=false,include_additional=false where role='consultant'; insert into consultant_rates(category,duration,price) values('Career',30,200);");
    await db.query("insert into partner_applications(id,customer_id,role,status,details) values($1,$2,'consultant','approved','{\"category\":\"Career\"}')", [consultantApplication, c]);
    await db.query("insert into partner_posts(id,partner_id,role,status,details) values($1,$2,'consultant','published','{\"mode\":\"Online\",\"category\":\"Career\",\"duration\":30}')", [consultantPost, consultantApplication]);
    await user(b);
    await db.query("select book_free_introduction($1,now()+interval '1 day')", [consultantPost]);
    await assert.rejects(db.query("select book_free_introduction($1,now()+interval '2 days')", [consultantPost]), /already been used or reserved/);
    await user(a);
    const code = await scalar('select get_referral_code()');
    await assert.rejects(db.query('select claim_referral($1)', [code]), /Invalid referral/);
    await assert.rejects(db.query("update profiles set role='admin' where id=$1", [a]), /permission denied/);
    await assert.rejects(db.query("insert into wallet_ledger(customer_id,amount,kind,event_key) values($1,1000,'referral','fake')", [a]), /row-level security/);
    await user(b);
    await db.query('select claim_referral($1)', [code]);
    await db.query('select claim_referral($1)', [code]);
    const key = randomUUID();
    const args = ['manpower', 'Plumber', 'service', { location: 'Bhopal', description: 'Tap leaking' }, key, v];
    const submit = 'select (submit_request($1,$2,$3,$4,$5,$6)).*';
    const booking = (await db.query(submit, args)).rows[0];
    assert.equal(Number(booking.quoted_total), 200);
    assert.equal((await db.query(submit, args)).rows[0].id, booking.id, 'Request retries are idempotent');
    await db.exec('reset role');
    await db.query("update service_requests set status='completed',payment_status='paid',paid_amount=200 where id=$1", [booking.id]);
    await db.query("update service_requests set status='completed',payment_status='paid' where id=$1", [booking.id]);
    await user(a);
    assert.equal(Number(await scalar('select wallet_balance()')), 80, 'Reward credited once');
    assert.equal(Number(await scalar('select count(*) from referrals')), 1);
    const own = (await db.query(submit, ['manpower', 'Plumber', 'service', {}, randomUUID(), v])).rows[0];
    const applied = await scalar('select reserve_wallet($1)', [own.id]);
    assert.deepEqual(applied, { remaining: 120, wallet_used: 80 });
    assert.deepEqual(await scalar('select reserve_wallet($1)', [own.id]), applied, 'Checkout retry cannot debit twice');
    assert.equal(Number(await scalar('select wallet_balance()')), 0);
    await user(c);
    await assert.rejects(db.query('select reserve_wallet($1)', [own.id]), /confirmed unpaid quote/);
    assert.equal(Number(await scalar('select count(*) from wallet_ledger')), 0, 'Wallet is private');
    await db.exec('reset role');
    await db.query("update service_requests set status='cancelled' where id=$1", [own.id]);
    await db.query("update service_requests set status='cancelled' where id=$1", [own.id]);
    await user(a);
    assert.equal(Number(await scalar('select wallet_balance()')), 80, 'Cancelled checkout returns wallet once');
    await db.exec('reset role');
    await db.query("update service_requests set payment_status='refunded' where id=$1", [booking.id]);
    await db.query("update service_requests set payment_status='refunded' where id=$1", [booking.id]);
    await user(a);
    assert.equal(Number(await scalar('select wallet_balance()')), 0, 'Refund reverses referral once');
    await user(c);
    await assert.rejects(db.query(submit, ['loans', 'Home Loan', 'loan', {}, randomUUID(), null]), /required/);
    const leadArgs = ['loans', 'Home Loan', 'loan', { fullName: 'Test Customer', phone: '9999999999', address: 'Bhopal', occupation: 'Salaried', income: 30000, amount: 100000, consent: true }, randomUUID(), null];
    const lead = (await db.query(submit, leadArgs)).rows[0];
    assert.equal((await db.query(submit, leadArgs)).rows[0].id, lead.id);
    await db.exec('reset role');
    assert.equal(Number(await scalar('select count(*) from excel_lead_outbox where lead_id=$1', [lead.id])), 1);
    assert.equal(await scalar('select status from excel_lead_outbox where lead_id=$1', [lead.id]), 'pending_configuration');
    // Expiry followed by refund must not remove the same unused credit twice.
    await db.query("insert into wallet_ledger(customer_id,amount,kind,event_key,booking_id,expires_at) values($1,25,'referral','expiry-test',$2,now()-interval '1 day')", [c, lead.id]);
    await user(c); assert.equal(Number(await scalar('select wallet_balance()')), 0);
    await db.exec('reset role');
    await db.query("insert into wallet_ledger(customer_id,amount,kind,event_key,booking_id) values($1,-25,'reversal','expiry-reversal',$2)", [c, lead.id]);
    await user(c); assert.equal(Number(await scalar('select wallet_balance()')), 0);
    await db.query('insert into customer_notification_preferences(customer_id,promotions) values($1,true)', [c]);
    await user(b); assert.equal(Number(await scalar('select count(*) from customer_notification_preferences')), 0, 'Profile preferences are private');
    await assert.rejects(db.query('select admin_dashboard_summary()'), /Admin access required/);
    await db.exec('reset role'); await db.query("update profiles set role='admin' where id=$1", [a]); await user(a);
    const adminSummary = await scalar('select admin_dashboard_summary()');
    assert.ok(Number(adminSummary.customers) >= 2, 'Authorized Admin reads real summary data');
    console.log('PASS: migrations, partner-role isolation, one-time consultant introductions, profile privacy, Admin authorization, RLS, self-referral prevention, idempotent requests/rewards/checkout/refunds, wallet expiry, and durable lead outbox.');
  } finally { await db.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
